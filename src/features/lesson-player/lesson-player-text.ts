/** Thay {mascot} trong mọi chuỗi (kể cả chuỗi do hàm trả về). */
function withMascotName(source: LessonText): LessonText {
  const output: Record<string, unknown> = {}
  for (const [key, value] of Object.entries(source)) {
    if (typeof value === 'string') output[key] = fillMascotName(value)
    else if (typeof value === 'function') output[key] = (...args: unknown[]) => fillMascotName(String((value as (...a: unknown[]) => unknown)(...args)))
    else output[key] = value
  }
  return output as LessonText
}

const VI_FILLED = withMascotName(VI)
const EN_FILLED = withMascotName(EN)

/** Hook lấy bộ chữ theo ngôn ngữ đang chọn. */
export function useLessonText(): LessonText {
  const { language } = useLanguage()
  return useMemo(() => (language === 'en' ? EN_FILLED : VI_FILLED), [language])
}

