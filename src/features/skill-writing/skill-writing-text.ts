const BY_LANGUAGE = { vi: VI, en: EN }

/** Chữ giao diện trình Writing theo ngôn ngữ đang chọn ({mascot} đã được thay tên). */
export function useWritingText(): WritingText {
  const { language } = useLanguage()
  return useMemo(() => {
    const source = BY_LANGUAGE[language]
    return { ...source, aiLoading: fillMascotName(source.aiLoading) }
  }, [language])
}

export type { WritingText }
